"""Generate the benchmark config matrix: 4 datasets x 5 arms -> configs/bench/.

Each config = a per-dataset pipeline (matched wide-R110, test eval) + a per-arm
controller. Run with:  python experiments/gen_bench_configs.py
"""

from __future__ import annotations

import os

import yaml

# --- per-dataset pipeline (everything except the controller) ---
DATASETS = {
    "c10":  dict(name="cifar10",      cutout=8,  flip=True,  stem_stride=1),
    "c100": dict(name="cifar100",     cutout=8,  flip=True,  stem_stride=1),
    "tiny": dict(name="tinyimagenet", cutout=16, flip=True,  stem_stride=2),
    "svhn": dict(name="svhn",         cutout=8,  flip=False, stem_stride=1),  # digits: no flip
}

# --- per-arm controller (the 5 methods) ---
ARMS = {
    "sammuon": dict(type="sam_catapult", base_optimizer="muon", lr=0.01, weight_decay=0.2,
                    rho=0.05, n_cycles=4, t_mult=2.0, warmup_steps=200, ns_dtype="bf16",
                    sam_freeze_bn=False, eos_rho=False),                       # ours
    "samsgd":  dict(type="sam_catapult", base_optimizer="sgd_momentum", lr=0.1, weight_decay=5.0e-4,
                    rho=0.20, n_cycles=4, t_mult=2.0, warmup_steps=200,
                    sam_freeze_bn=False, eos_rho=False),                       # published SAM (Foret 2021)
    "muon":    dict(type="cyclic_catapult", base_optimizer="muon", lr=0.01, weight_decay=0.2,
                    n_cycles=4, t_mult=2.0, warmup_steps=200, ns_dtype="bf16"),  # published Muon (Jordan 2024)
    "cyclicj": dict(type="cyclic_catapult", base_optimizer="sgd_momentum", lr=0.1, weight_decay=5.0e-4,
                    n_cycles=4, t_mult=2.0, warmup_steps=200),                 # SGDR (Loshchilov 2017)
    "strongsgd": dict(type="cyclic_catapult", base_optimizer="sgd_momentum", lr=0.1, weight_decay=5.0e-4,
                      n_cycles=1, warmup_steps=200),                          # single-cosine SGD
}
_COMMON_CTRL = dict(min_lr=0.0, momentum=0.9, nesterov=True)


def build(ds_key, arm_key):
    ds, arm = DATASETS[ds_key], ARMS[arm_key]
    ctrl = {**arm, **_COMMON_CTRL}
    # keep key order readable: type/base first
    ctrl = {"type": ctrl.pop("type"), "base_optimizer": ctrl.pop("base_optimizer"), **ctrl}
    cfg = {
        "run_name": f"{ds_key}_{arm_key}",
        "seed": 42, "device": "auto", "deterministic": False,
        "epochs": 100, "batch_size": 128, "mixed_precision": "bf16", "grad_clip": 2.0,
        "model": "resnet110", "initial_channels": 64, "bn_momentum": 0.01,
        "stem_stride": ds["stem_stride"],
        "dataset": {"name": ds["name"], "validation_split": 0},
        "augment": {"enabled": True, "cutout": ds["cutout"], "color_jitter": 0.1, "flip": ds["flip"]},
        "controller": ctrl,
        "probes": {"enabled": False},
    }
    return cfg


def main():
    out = os.path.join("configs", "bench")
    os.makedirs(out, exist_ok=True)
    n = 0
    for ds_key in DATASETS:
        for arm_key in ARMS:
            cfg = build(ds_key, arm_key)
            path = os.path.join(out, f"{ds_key}_{arm_key}.yaml")
            with open(path, "w") as f:
                f.write(f"# benchmark: {ds_key} / {arm_key} (auto-generated by gen_bench_configs.py)\n")
                yaml.safe_dump(cfg, f, sort_keys=False, default_flow_style=False)
            n += 1
    print(f"wrote {n} configs to {out}/")


if __name__ == "__main__":
    main()
