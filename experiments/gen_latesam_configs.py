"""Generate the late-phase-SAM rival configs (arm R) -> configs/latesam/.

Re-runs the closest published *allocation* method, late-phase SAM
(arXiv:2410.10373), inside this pipeline so it can be compared on wall-clock.
`arm_O` is not a stand-in for it: arm O switches SAM on mid-cycle over a
Muon-catapult base, whereas the published method is plain SGD on a standard
schedule with SAM enabled for a late contiguous phase.

Every choice below is made so the rival is not handicapped:

  * pipeline (model, augmentation, epochs, batch) is copied verbatim from that
    dataset's `strongsgd` bench config, so nothing differs but the controller;
  * SGD hyper-parameters are our *tuned* ones (lr 0.1, wd 5e-4) and rho is the
    *tuned* SAM+SGD value from the bench (0.2), not a guess;
  * `n_cycles: 1` -- a standard single cosine anneal, which is the schedule the
    paper assumes, rather than our cyclic restarts;
  * `sam_start_frac: 0.43` -- budget-matched to Temperon, which spends SAM on
    57 of 100 epochs, so both methods buy the same number of two-pass epochs;
  * no rho ramp -- the published method does not ramp. The ramp is a component
    of ours, and arm O had one and still failed, so it is not what carries our
    result.

Run:  python experiments/gen_latesam_configs.py
"""

from __future__ import annotations

import os

import yaml

DATASETS = ["c100", "tiny", "c10", "svhn"]
SRC_DIR = "configs/bench"
OUT_DIR = "configs/latesam"

# Tuned in the benchmark sweep; see configs/bench/<ds>_samsgd.yaml.
RHO = 0.2
SAM_START_FRAC = 0.43   # 57 of 100 epochs get SAM == Temperon's tail length


def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    for ds in DATASETS:
        src = os.path.join(SRC_DIR, f"{ds}_strongsgd.yaml")
        with open(src) as f:
            cfg = yaml.safe_load(f)

        sgd = cfg["controller"]
        cfg["run_name"] = f"{ds}_latesam"
        cfg["controller"] = {
            "type": "sam_catapult",
            "base_optimizer": "sgd_momentum",
            "lr": sgd["lr"],
            "weight_decay": sgd["weight_decay"],
            "rho": RHO,
            "n_cycles": 1,              # standard schedule, not cyclic restarts
            "warmup_steps": sgd["warmup_steps"],
            "min_lr": sgd["min_lr"],
            "momentum": sgd["momentum"],
            "nesterov": sgd["nesterov"],
            "sam_freeze_bn": False,
            "eos_rho": False,
            "sam_start_frac": SAM_START_FRAC,
            # no sam_rho_ramp_steps: the published method uses a fixed radius
        }

        out = os.path.join(OUT_DIR, f"{ds}_latesam.yaml")
        header = (
            f"# arm R: late-phase SAM (arXiv:2410.10373) on {ds}, re-run in this\n"
            f"# pipeline for a wall-clock-comparable rival. Auto-generated by\n"
            f"# experiments/gen_latesam_configs.py -- edit that, not this file.\n"
            f"# Pipeline copied from {src}; SAM budget matched to Temperon\n"
            f"# ({int(round((1 - SAM_START_FRAC) * cfg['epochs']))} of "
            f"{cfg['epochs']} epochs two-pass).\n"
        )
        with open(out, "w") as f:
            f.write(header)
            yaml.safe_dump(cfg, f, sort_keys=False, default_flow_style=False)
        print(f"wrote {out}")


if __name__ == "__main__":
    main()
